def dot_product(v: List[float], w:List[float]) -> float:
    return sum(item1*item2 for item1, item2 in zip(v,w))

def matrix_multiply (A: List[Vector], B: List[Vector]) -> List[Vector]:

    assert len(A[0]) == len(B), "the number of columns in A equals the number of rows in B for matrix multiplication."

    return [[dot_product(get_col(B, j), get_row(A, i)) for j in range(len(B[0]))] for i in range(len(A))]

