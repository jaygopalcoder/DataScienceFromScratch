Vector = List[float]

def shape (m: List[Vector]) -> Tuple[int,int]:
    assert all(len(vector) == len(m[0]) for vector in m ), "length of all row of matrix should be same."
    return (len(m),len(m[0]))

def get_row (A: List[Vector], i: int) -> List[Vector]:
    assert i < len(A), f"{i}th index row doesn't exist in matrix of shape {(len(A), len(A[0]))}"
    return A[i]

def get_col (A: List[Vector], i: int) -> List[Vector]:
    assert i < len(A[0]), f"{i}th index column doesn't exist in matrix of shape {(len(A), len(A[0]))}"
    return [A[j][i] for j in range(len(A))]

def make_matrix(num_rows: int, num_cols: int, entry_fn: Callable[[int, int], float]) -> List[List[float]]: 
    assert num_cols > 0 and num_rows > 0, "no of rows and column shouldn't be empty"
    return [[entry_fn(i,j) for j in range(num_cols)] for i in range(num_rows)] 
# outer loop will decide how many row we have to generate where inner loop will decide how many columns we have to generate

